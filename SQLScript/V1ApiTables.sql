-- =========================================================================
-- Tables for the new API gateway (SilaApi/Plus.Api).
--
--   1. PLS.V1ApiIdentity            -- ERP username -> stable token subject ("sub")
--   2. PLS.V1ApiSession             -- one row per login session ("sid")
--   3. PLS.V1ApiRefreshToken        -- SHA-256 hashes of refresh tokens (never the token)
--   4. PLS.V1ApiOperationPermission -- allowlist of proc + operation /api/v2/exec may run
--
-- Tables 1-3 are used only by PLS.APIPlusAuthSessionOperation (Login / Refresh /
-- Validate / Logout / ChangePassword) -- that SP is NOT in this script.
-- Table 4 is read by SqlOperationPermissionStore.cs on every /exec call.
--
-- All times are UTC (SYSUTCDATETIME) -- the API treats ExpiresAt as UTC.
-- Idempotent: safe to run more than once. Deploy via SSMS or live-db.
-- =========================================================================

IF SCHEMA_ID('PLS') IS NULL EXEC('CREATE SCHEMA [PLS]');
GO

-- -------------------------------------------------------------------------
-- 1. PLS.V1ApiIdentity
--   Subject         -- goes into the JWT "sub" claim; never changes for a user,
--                      even if the ERP username is renamed later.
--   Username        -- ERP username (dbo.UserMaster.Username in SILA101);
--                      goes into the "erp_user" claim and becomes @User in every SP.
--   CredentialStamp -- replaced on every password change; sessions created with an
--                      older stamp are dead (one password change logs out everywhere).
-- -------------------------------------------------------------------------
IF OBJECT_ID('PLS.V1ApiIdentity', 'U') IS NULL
CREATE TABLE [PLS].[V1ApiIdentity] (
    Subject         UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_V1ApiIdentity_Subject DEFAULT (NEWID()),
    Username        NVARCHAR(100)    NOT NULL,
    CredentialStamp UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_V1ApiIdentity_Stamp DEFAULT (NEWID()),
    CreatedAt       DATETIME2(3)     NOT NULL CONSTRAINT DF_V1ApiIdentity_Created DEFAULT (SYSUTCDATETIME()),
    LastLoginAt     DATETIME2(3)     NULL,
    CONSTRAINT PK_V1ApiIdentity PRIMARY KEY (Subject),
    CONSTRAINT UQ_V1ApiIdentity_Username UNIQUE (Username)
);
GO

-- -------------------------------------------------------------------------
-- 2. PLS.V1ApiSession
--   SessionId           -- generated by the API at login; the JWT "sid" claim.
--   ForcePasswordChange -- 1 = expired password: short change-password-only session.
--   ExpiresAt           -- hard end of the session (7 days, or 10 min if forced change);
--                          refresh never extends it.
--   RevokedAt/Reason    -- set on Logout, password change, refresh-token reuse,
--                          or user disabled. A revoked session fails 'Validate'.
-- -------------------------------------------------------------------------
IF OBJECT_ID('PLS.V1ApiSession', 'U') IS NULL
CREATE TABLE [PLS].[V1ApiSession] (
    SessionId           UNIQUEIDENTIFIER NOT NULL,
    Subject             UNIQUEIDENTIFIER NOT NULL,
    CredentialStamp     UNIQUEIDENTIFIER NOT NULL,
    ForcePasswordChange BIT              NOT NULL CONSTRAINT DF_V1ApiSession_Force DEFAULT (0),
    CreatedAt           DATETIME2(3)     NOT NULL CONSTRAINT DF_V1ApiSession_Created DEFAULT (SYSUTCDATETIME()),
    ExpiresAt           DATETIME2(3)     NOT NULL,
    LastSeenAt          DATETIME2(3)     NULL,
    CreatedIP           VARCHAR(45)      NULL,
    LastIP              VARCHAR(45)      NULL,
    RevokedAt           DATETIME2(3)     NULL,
    RevokedReason       NVARCHAR(50)     NULL,   -- 'Logout' | 'PasswordChanged' | 'RefreshReuse' | 'Disabled'
    CONSTRAINT PK_V1ApiSession PRIMARY KEY (SessionId),
    CONSTRAINT FK_V1ApiSession_Identity FOREIGN KEY (Subject) REFERENCES [PLS].[V1ApiIdentity] (Subject)
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_V1ApiSession_Subject_Active'
               AND object_id = OBJECT_ID('PLS.V1ApiSession'))
    -- Not a filtered index: those need ANSI_WARNINGS ON for every later DML on the
    -- table, and the live gateway connection runs with it OFF.
    CREATE INDEX IX_V1ApiSession_Subject_Active ON [PLS].[V1ApiSession] (Subject, ExpiresAt)
        INCLUDE (RevokedAt);
GO

-- -------------------------------------------------------------------------
-- 3. PLS.V1ApiRefreshToken
--   TokenHash      -- SHA-256 of the 32 random bytes (LocalTokens.HashRefresh).
--                     The raw refresh token is never stored.
--   ConsumedAt     -- set when used once. Presenting a consumed hash again = token
--                     theft -> revoke the whole session (RevokedReason 'RefreshReuse').
--   ReplacedByHash -- the hash issued in exchange, for the audit chain.
-- -------------------------------------------------------------------------
IF OBJECT_ID('PLS.V1ApiRefreshToken', 'U') IS NULL
CREATE TABLE [PLS].[V1ApiRefreshToken] (
    TokenHash      BINARY(32)       NOT NULL,
    SessionId      UNIQUEIDENTIFIER NOT NULL,
    CreatedAt      DATETIME2(3)     NOT NULL CONSTRAINT DF_V1ApiRefreshToken_Created DEFAULT (SYSUTCDATETIME()),
    ConsumedAt     DATETIME2(3)     NULL,
    ReplacedByHash BINARY(32)       NULL,
    CONSTRAINT PK_V1ApiRefreshToken PRIMARY KEY (TokenHash),
    CONSTRAINT FK_V1ApiRefreshToken_Session FOREIGN KEY (SessionId)
        REFERENCES [PLS].[V1ApiSession] (SessionId) ON DELETE CASCADE
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_V1ApiRefreshToken_Session'
               AND object_id = OBJECT_ID('PLS.V1ApiRefreshToken'))
    CREATE INDEX IX_V1ApiRefreshToken_Session ON [PLS].[V1ApiRefreshToken] (SessionId);
GO

-- -------------------------------------------------------------------------
-- 4. PLS.V1ApiOperationPermission
--   ProcedureName / OperationName -- BINARY collation: must match the request's
--       spelling exactly ('PLS.APIPlusOperationV1' <> 'Pls.APIPlusOperationV1').
--   Enabled               -- 0 = denied (default). Missing row = denied.
--   AllowExternal         -- also allow callers outside Gateway:InternalNetworks.
--   AllowedParametersJson -- JSON array of extraParams names this operation accepts,
--       e.g. N'["LineMember"]'. N'[]' = none. Reserved names (User, IP, ...) are
--       always refused by the gateway regardless of this list.
--   StatusResultSet       -- index of the result set carrying State/Message, or NULL.
-- Columns read by SqlOperationPermissionStore.cs:
--   Enabled, AllowExternal, AllowedParametersJson, StatusResultSet.
-- -------------------------------------------------------------------------
IF OBJECT_ID('PLS.V1ApiOperationPermission', 'U') IS NULL
CREATE TABLE [PLS].[V1ApiOperationPermission] (
    ProcedureName         NVARCHAR(257) COLLATE Latin1_General_BIN2 NOT NULL,
    OperationName         NVARCHAR(100) COLLATE Latin1_General_BIN2 NOT NULL,
    Enabled               BIT           NOT NULL CONSTRAINT DF_V1ApiOpPerm_Enabled DEFAULT (0),
    AllowExternal         BIT           NOT NULL CONSTRAINT DF_V1ApiOpPerm_External DEFAULT (0),
    AllowedParametersJson NVARCHAR(MAX) NOT NULL CONSTRAINT DF_V1ApiOpPerm_Params DEFAULT (N'[]'),
    StatusResultSet       INT           NULL,
    Notes                 NVARCHAR(400) NULL,
    ModifiedBy            NVARCHAR(100) NULL,
    ModifiedAt            DATETIME2(3)  NOT NULL CONSTRAINT DF_V1ApiOpPerm_Modified DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_V1ApiOperationPermission PRIMARY KEY (ProcedureName, OperationName),
    CONSTRAINT CK_V1ApiOpPerm_ParamsJson CHECK (ISJSON(AllowedParametersJson) = 1
                                                AND LEFT(LTRIM(AllowedParametersJson), 1) = N'['),
    CONSTRAINT CK_V1ApiOpPerm_StatusRS  CHECK (StatusResultSet IS NULL OR StatusResultSet BETWEEN 0 AND 31)
);
GO

-- Seed: the one reviewed read operation (per SilaApi/docs/IIS-DEPLOYMENT.md). Every other
-- operation the React app uses needs its own reviewed row before cutover.
IF NOT EXISTS (SELECT 1 FROM [PLS].[V1ApiOperationPermission]
               WHERE ProcedureName = N'Pls.APIPlusOperationV1' AND OperationName = N'GetPagesAndGroups')
    INSERT [PLS].[V1ApiOperationPermission]
        (ProcedureName, OperationName, Enabled, AllowExternal, AllowedParametersJson, Notes)
    VALUES (N'Pls.APIPlusOperationV1', N'GetPagesAndGroups', 1, 1, N'[]', N'Seed: menu/pages load');
GO

